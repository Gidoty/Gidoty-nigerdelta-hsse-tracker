import { defaultEvidenceStatus } from '../utils/evidenceStatus.js'

const HOUR = 60 * 60 * 1000
const DAY = 24 * HOUR

function displayCoords(lat, lng) {
  return { lat: Math.round(lat * 100) / 100, lng: Math.round(lng * 100) / 100 }
}

function baseReport(overrides) {
  const lat = overrides.lat
  const lng = overrides.lng
  return {
    id: `demo-${overrides.id}`,
    referenceNumber: `HSSE-DEMO${overrides.id}`,
    submittedAt: new Date(Date.now() - overrides.ageMs).toISOString(),
    status: overrides.status ?? 'submitted',
    dataClass: 'demo',
    location: {
      gps: { lat, lng, accuracy: 25, capturedAt: Date.now() - overrides.ageMs },
      display: displayCoords(lat, lng),
      state: overrides.state,
      lga: overrides.lga,
      landmark: overrides.landmark,
    },
    incident: {
      type: overrides.type,
      subType: overrides.subType ?? null,
      severity: overrides.severity,
      duration: overrides.duration ?? 'ongoing',
      dateTime: new Date(Date.now() - overrides.ageMs).toISOString(),
      description: overrides.description,
      isDemoData: true,
    },
    evidence: { photos: [], photoCount: 0 },
    health: {
      healthImpact: overrides.healthImpact ?? false,
      symptoms: overrides.symptoms ?? [],
      affectedCount: overrides.affectedCount ?? null,
    },
    contact: {
      anonymous: true,
      name: null,
      phone: null,
      willingToContact: false,
      willingToWitness: false,
      wantsNotification: false,
    },
    evidenceStatus: overrides.evidenceStatus ?? defaultEvidenceStatus(),
    regulatory: {
      nosdraNotified: overrides.nosdraNotified ?? false,
      nosdraNotifiedAt: null,
      nuprcNotified: false,
      nuprcNotifiedAt: null,
      operatorResponse: overrides.operatorResponse ?? null,
      jivScheduled: false,
      jivDate: null,
      jivCompleted: false,
      cleanupStatus: overrides.cleanupStatus ?? 'pending',
    },
    methane: { calculated: false, estimatedCH4: null, estimatedCO2e: null },
    audit: {
      consentVersion: 'NDPA-2023-v1',
      consentTimestamp: Date.now() - overrides.ageMs,
      language: 'en',
      userAgent: 'demo',
      reportHash: 'demo-data-not-hashed',
    },
    integrity: {
      algorithm: null,
      canonicalization: 'legacy-v0-noncanonical',
      payloadHash: 'demo-data-not-hashed',
      photoHashes: [],
      hashedAt: null,
    },
    events: [],
  }
}

